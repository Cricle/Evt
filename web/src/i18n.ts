export const translate = (locale: AppLocale, key: string, fallback?: string) =>
  (messages[locale][key] as string | undefined) ?? fallback ?? key;

export const useI18n = () => {
  const storeMain = useStoreMain();
  const { locale } = storeToRefs(storeMain);

  const naiveLocale = computed(() => naiveLocales[locale.value].locale);
  const naiveDateLocale = computed(() => naiveLocales[locale.value].dateLocale);

  const t = (key: string, fallback?: string) => translate(locale.value, key, fallback);

  return {
    locale,
    naiveLocale,
    naiveDateLocale,
    t,
  };
};
